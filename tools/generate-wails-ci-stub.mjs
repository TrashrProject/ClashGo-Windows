import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const srcRoot = path.join(root, 'web', 'src');
const outDir = path.join(root, 'web', 'wailsjs', 'go', 'main');
const methods = new Set();

const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (entry.isFile() && /\.(ts|tsx)$/.test(entry.name)) {
      const source = fs.readFileSync(full, 'utf8');
      const re = /import\s*\{([^}]*)\}\s*from\s*['"][^'"]*wailsjs\/go\/main\/App['"]/gs;
      for (const match of source.matchAll(re)) {
        for (const raw of match[1].split(',')) {
          const name = raw.trim().split(/\s+as\s+/)[0].trim();
          if (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)) methods.add(name);
        }
      }
    }
  }
};
walk(srcRoot);

fs.mkdirSync(outDir, { recursive: true });

const names = [...methods].sort();
const dts = [
  '// Generated only for lightweight Core CI. Real Wails bindings are generated by the Windows build.',
  ...names.map((name) => `export function ${name}(...args: any[]): Promise<any>;`),
  '',
].join('\n');

const js = [
  '// Generated only for lightweight Core CI. Never shipped as a production binding.',
  ...names.map((name) => `export function ${name}() { return Promise.reject(new Error("CI Wails stub: ${name}")); }`),
  '',
].join('\n');

fs.writeFileSync(path.join(outDir, 'App.d.ts'), dts, 'utf8');
fs.writeFileSync(path.join(outDir, 'App.js'), js, 'utf8');
console.log(`Generated lightweight CI Wails stub for ${names.length} imported methods.`);
